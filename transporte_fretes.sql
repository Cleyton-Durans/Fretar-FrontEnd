CREATE DATABASE transporte_fretes;

-- Depois conecte-se ao banco transporte_fretes antes de executar as instruções abaixo.

CREATE TABLE "user" (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    phone VARCHAR(20),
    address VARCHAR(255),
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    avatar VARCHAR(500)
);

CREATE TABLE driver (
    driver_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    phone VARCHAR(20),
    address VARCHAR(255),
    cnh VARCHAR(30) NOT NULL UNIQUE,
    status_online BOOLEAN DEFAULT FALSE,
    avatar VARCHAR(500),
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vehicle (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id INTEGER NOT NULL,
    vehicle_type VARCHAR(100),
    license_plate VARCHAR(15),
    capacity_load NUMERIC(12,2),
    CONSTRAINT fk_vehicle_driver FOREIGN KEY (driver_id) REFERENCES driver(driver_id)
);

CREATE TABLE shipping (
    shipping_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    driver_id INTEGER,
    origin VARCHAR(255),
    destination VARCHAR(255),
    about_load VARCHAR(500),
    recommended_vehicle VARCHAR(100),
    status VARCHAR(50),
    creation_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    conclusion_date TIMESTAMP,
    value NUMERIC(12,2),
    CONSTRAINT fk_shipping_user FOREIGN KEY (user_id) REFERENCES "user"(user_id),
    CONSTRAINT fk_shipping_driver FOREIGN KEY (driver_id) REFERENCES driver(driver_id)
);

CREATE TABLE payment_method (
    payment_method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    stripe_customer_id VARCHAR(255),
    stripe_payment_method_id VARCHAR(255),
    type VARCHAR(50),
    last_4_digits VARCHAR(4),
    card_brand VARCHAR(50),
    CONSTRAINT fk_payment_method_user FOREIGN KEY (user_id) REFERENCES "user"(user_id)
);

CREATE TABLE payment (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipping_id INTEGER NOT NULL UNIQUE,
    payment_method_id INTEGER NOT NULL,
    stripe_payment_intent_id VARCHAR(255),
    value NUMERIC(12,2),
    payment_status VARCHAR(50),
    payment_date TIMESTAMP,
    CONSTRAINT fk_payment_shipping FOREIGN KEY (shipping_id) REFERENCES shipping(shipping_id),
    CONSTRAINT fk_payment_method FOREIGN KEY (payment_method_id) REFERENCES payment_method(payment_method_id)
);

CREATE TABLE shipping_driver (
    shipping_id INTEGER NOT NULL,
    driver_id INTEGER NOT NULL,
    driver_status VARCHAR(50),
    reply_date TIMESTAMP,
    CONSTRAINT pk_shipping_driver PRIMARY KEY (shipping_id, driver_id),
    CONSTRAINT fk_shipping_driver_shipping FOREIGN KEY (shipping_id) REFERENCES shipping(shipping_id),
    CONSTRAINT fk_shipping_driver_driver FOREIGN KEY (driver_id) REFERENCES driver(driver_id)
);

CREATE TABLE evaluation (
    evaluation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    shipping_id INTEGER NOT NULL,
    rating NUMERIC(3,2) NOT NULL,
    comment TEXT,
    CONSTRAINT fk_evaluation_driver FOREIGN KEY (driver_id) REFERENCES driver(driver_id),
    CONSTRAINT fk_evaluation_user FOREIGN KEY (user_id) REFERENCES "user"(user_id),
    CONSTRAINT fk_evaluation_shipping FOREIGN KEY (shipping_id) REFERENCES shipping(shipping_id),
    CONSTRAINT uk_evaluation_user_shipping UNIQUE (user_id, shipping_id),
    CONSTRAINT ck_evaluation_rating CHECK (rating BETWEEN 1 AND 5)
);
